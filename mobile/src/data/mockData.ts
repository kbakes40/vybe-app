export const getTrackById = (id: string): Track | undefined => {
  return tracks.find(t => t.id === id);
};

export const getArtistById = (id: string): Artist | undefined => {
  return artists.find(a => a.id === id);
};

export const getAlbumById = (id: string): Album | undefined => {
  return albums.find(a => a.id === id);
};

export const getPlaylistById = (id: string): Playlist | undefined => {
  return playlists.find(p => p.id === id);
};

export const getTracksByArtist = (artistId: string): Track[] => {
  return tracks.filter(t => t.artistId === artistId);
};

export const getAlbumsByArtist = (artistId: string): Album[] => {
  return albums.filter(a => a.artistId === artistId);
};

export const getTracksFromPlaylist = (playlistId: string): Track[] => {
  const playlist = getPlaylistById(playlistId);
  if (!playlist) return [];
  return playlist.tracks.map(id => getTrackById(id)).filter((t): t is Track => t !== undefined);
};

export const getTracksFromAlbum = (albumId: string): Track[] => {
  const album = getAlbumById(albumId);
  if (!album) return [];
  return album.tracks.map(id => getTrackById(id)).filter((t): t is Track => t !== undefined);
};

export const getLikedTracks = (): Track[] => {
  return tracks.filter(t => t.isLiked);
};

export const formatDuration = (seconds: number): string => {
  const mins = Math.floor(seconds / 60);
  const secs = seconds % 60;
  return `${mins}:${secs.toString().padStart(2, '0')}`;
};

export const formatFollowers = (count: number): string => {
  if (count >= 1000000) {
    return `${(count / 1000000).toFixed(1)}M`;
  }
  if (count >= 1000) {
    return `${(count / 1000).toFixed(0)}K`;
  }
  return count.toString();
};
