#!/usr/bin/env node
import { execSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(here, '..', 'src', 'constants', 'buildInfo.generated.ts');

function safe(cmd, fallback) {
  try {
    return execSync(cmd, { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return fallback;
  }
}

const commit = safe('git rev-parse --short=8 HEAD', 'nogit');
const branch = safe('git rev-parse --abbrev-ref HEAD', 'nogit');
const dirty = safe('git status --porcelain', '') !== '';
const bundledAt = new Date().toISOString();

const body = `// Auto-generated by scripts/write-build-info.mjs. Do not edit.
export const BUILD_COMMIT = '${commit}${dirty ? '-dirty' : ''}';
export const BUILD_BRANCH = '${branch}';
export const BUILD_BUNDLED_AT = '${bundledAt}';
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, body);
process.stdout.write(`[build-info] ${commit}${dirty ? '-dirty' : ''} (${branch}) @ ${bundledAt}\n`);
